#!/usr/bin/env bash
set -euo pipefail
hostname=${1:?Usage: sudo bash install.sh PUBLIC_HOSTNAME}
prepare_only=${2:-}
[[ -z "$prepare_only" || "$prepare_only" == --prepare-only ]] || { echo 'Unsupported option' >&2; exit 1; }
[[ "$hostname" =~ ^[a-zA-Z0-9][a-zA-Z0-9.-]+$ ]] || { echo 'Invalid hostname' >&2; exit 1; }
[[ $(id -u) == 0 ]] || { echo 'Run this installer as root' >&2; exit 1; }
script_dir=$(cd -- "$(dirname -- "$0")" && pwd)
config_dir=/etc/mygo-fighter
legacy_env=/etc/mygo-fighter.env
legacy_unit=/etc/systemd/system/mygo-fighter.service
legacy=0
test -f "$legacy_env" && legacy=1
test -f "$legacy_unit" && legacy=1
# This installer owns the Caddy configuration on a dedicated test host. Refuse
# to replace an existing unrelated Caddy deployment.
if command -v caddy >/dev/null && ! test -f /etc/caddy/Caddyfile.before-mygo; then
  echo 'Caddy already exists. Integrate deploy/Caddyfile manually before installing.' >&2
  exit 1
fi
export DEBIAN_FRONTEND=noninteractive
apt-get update
apt-get install -y --no-install-recommends openjdk-21-jre-headless caddy curl openssl
id mygo >/dev/null 2>&1 || useradd --system --user-group --home-dir /srv/mygo-fighter --no-create-home --shell /usr/sbin/nologin mygo
install -d -o root -g mygo -m 0750 /srv/mygo-fighter /srv/mygo-fighter/releases
install -d -o root -g mygo -m 0750 "$config_dir"

# Read one KEY=value line without executing the file as a shell script.
read_env() {
  local key=$1 file=$2 value=
  if test -f "$file"; then
    value=$(sed -n "s/^[[:space:]]*$key[[:space:]]*=[[:space:]]*//p" "$file" | tail -n 1)
    value=${value%$'\r'}
    value=${value%\"}; value=${value#\"}
    value=${value%\'}; value=${value#\'}
  fi
  printf '%s' "$value"
}
install_env() {
  local source=$1 target=$2
  if test -f "$target"; then
    echo "Keeping existing $target."
  else
    install -o root -g mygo -m 0640 "$source" "$target"
    echo "Installed $target."
  fi
}

install_env "$script_dir/env/base.env.example" "$config_dir/base.env"
install_env "$script_dir/env/edge.env.example" "$config_dir/edge.env"
install_env "$script_dir/env/lobby.env.example" "$config_dir/lobby.env"
install_env "$script_dir/env/rooms.env.example" "$config_dir/rooms.env"

# One shared secret authenticates every loopback service-to-service call. It is
# generated once; rerunning the installer never rotates it.
if test -z "$(read_env INTERNAL_SECRET "$config_dir/base.env")"; then
  secret=$(openssl rand -hex 32)
  printf '\n# Generated by install.sh; every service on this host must share it.\nINTERNAL_SECRET=%s\n' "$secret" >> "$config_dir/base.env"
  echo "Generated INTERNAL_SECRET in $config_dir/base.env."
fi
if test -z "$(read_env ROOMS_INSTANCES "$config_dir/base.env")"; then
  printf '\nROOMS_INSTANCES="a"\n' >> "$config_dir/base.env"
  echo "No ROOMS_INSTANCES found; defaulted to \"a\" in $config_dir/base.env."
fi

instances=$(read_env ROOMS_INSTANCES "$config_dir/base.env")
instances=${instances:-a}
instance_list=()
for instance in ${instances//,/ }; do
  [[ "$instance" =~ ^[a-z0-9][a-z0-9-]*$ ]] || { echo "Invalid ROOMS_INSTANCES entry: $instance" >&2; exit 1; }
  instance_list+=("$instance")
done
test ${#instance_list[@]} -gt 0 || { echo 'ROOMS_INSTANCES lists no instances' >&2; exit 1; }

install -o root -g root -m 0644 "$script_dir/mygo-edge.service" /etc/systemd/system/mygo-edge.service
install -o root -g root -m 0644 "$script_dir/mygo-lobby.service" /etc/systemd/system/mygo-lobby.service
install -o root -g root -m 0644 "$script_dir/mygo-rooms@.service" /etc/systemd/system/mygo-rooms@.service
install -d -o root -g root -m 0755 /opt/mygo-fighter
install -o root -g root -m 0755 "$script_dir/activate.sh" "$script_dir/rollback.sh" /opt/mygo-fighter/
if ! test -f /etc/caddy/Caddyfile.before-mygo; then
  cp -a /etc/caddy/Caddyfile /etc/caddy/Caddyfile.before-mygo
fi
# Render a single explicit hostname. No on-demand certificates or wildcard host matching.
sed "s/{\$GAME_HOSTNAME}/$hostname/" "$script_dir/Caddyfile" > /etc/caddy/Caddyfile
caddy validate --config /etc/caddy/Caddyfile --adapter caddyfile
systemctl daemon-reload
rooms_units=()
for instance in "${instance_list[@]}"; do rooms_units+=("mygo-rooms@$instance"); done
systemctl enable caddy mygo-edge mygo-lobby "${rooms_units[@]}"
# The new layout owns port 8080. Leave the old unit file for comparison, but
# stop it so both layouts can never fight over the public port.
if test -f "$legacy_unit" && test "$prepare_only" != --prepare-only; then
  systemctl disable --now mygo-fighter 2>/dev/null || true
  echo 'Disabled and stopped the legacy mygo-fighter.service.'
fi
if test "$prepare_only" = --prepare-only; then
  echo 'Prepared role units; the legacy service remains running until activation.'
  systemctl reload caddy
else
  systemctl restart caddy
fi
echo "Host installed with mygo-edge, mygo-lobby and ${#instance_list[@]} rooms instance(s): ${instance_list[*]}."
echo 'Upload a packaged release and run deploy/activate.sh.'
if test "$legacy" -eq 1; then
  cat >&2 <<'NOTE'

Migration note for this pre-2026-10-29 host
-------------------------------------------
The previous single-unit layout used mygo-fighter.service and
/etc/mygo-fighter.env. Both are preserved, but the new edge/lobby/rooms units
do not read /etc/mygo-fighter.env. Before activating the new release:

  1. Compare the old values with /etc/mygo-fighter/{base,edge,lobby,rooms}.env.
     HOST, PORT, WEB_ROOT and TRUST_LOCAL_PROXY belong in edge.env; MAX_ROOMS
     belongs in lobby.env (global ceiling) and rooms.env (per-instance ceiling).
  2. Add any extra rooms instance IDs to ROOMS_INSTANCES in base.env, then
     rerun this installer to enable their template units.
  3. Install the packaged release with
        sudo bash /opt/mygo-fighter/activate.sh ARCHIVE RELEASE_ID [COMMIT]
  4. Keep the disabled legacy unit and /etc/mygo-fighter.env while a legacy
     release is retained as previous; rollback needs both. Remove them only
     after no retained rollback target uses the single-unit layout.
NOTE
fi
