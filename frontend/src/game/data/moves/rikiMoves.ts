import type { Move } from "../../objects/Move";
import { NORMAL_BUTTONS } from "../rules";

export function registerRikiMoves(MOVES: Record<string, Move>): void {
  const rikiNames = [
    "轻鼓棒",
    "交叉双棒",
    "重拍砸棒",
    "低踢",
    "侧踢",
    "转身扫踢",
  ];
  for (const stance of ["standing", "crouch", "air"])
    NORMAL_BUTTONS.forEach((button, i) => {
      const suffix = (stance === "standing" ? "" : stance + "_") + button,
        source = MOVES[suffix];
      MOVES["riki_" + suffix] = {
        ...source,
        rikiOnly: true,
        name:
          (stance === "crouch" ? "蹲下·" : stance === "air" ? "空中·" : "") +
          rikiNames[i],
        damage: [7, 11, 20, 6, 10, 17][i] - (stance === "standing" ? 0 : 1),
        duration: source.duration + (i === 2 ? 40 : 0),
        reach: source.reach! + (i < 3 ? 12 : 0),
      };
    });
  Object.assign(MOVES, {
    rikiRoll: {
      name: "滚奏连打",
      command: "I / 2P 小键盘4",
      category: "special",
      rikiOnly: true,
      ground: true,
      cost: 20,
      duration: 650,
      start: 100,
      end: 490,
      damage: 15,
      stun: 300,
      push: 10,
      reach: 190,
      cancelAt: 400,
      pulses: [100, 250, 400].map((at) => ({ at, damage: 5, reach: 190 })),
    },
    rikiRush: {
      name: "踩镲抢拍",
      command: "C / 2P Home",
      category: "special",
      rikiOnly: true,
      ground: true,
      cost: 15,
      duration: 500,
      start: 160,
      end: 250,
      damage: 12,
      stun: 350,
      push: 35,
      reach: 170,
      dashSpeed: 1000,
    },
    rikiOverhead: {
      name: "反拍砸击",
      command: "U / 2P 小键盘*",
      category: "special",
      rikiOnly: true,
      ground: true,
      cost: 20,
      duration: 760,
      start: 300,
      end: 390,
      damage: 21,
      stun: 360,
      push: 130,
      reach: 195,
      vertical: 140,
      level: "high",
    },
    rikiShock: {
      name: "低音落震",
      command: "T / 2P 小键盘Enter",
      category: "special",
      rikiOnly: true,
      ground: true,
      projectile: true,
      cost: 30,
      duration: 700,
      start: 220,
      end: 240,
      damage: 18,
      chip: 3,
      stun: 310,
      push: 160,
      speed: 480,
      lifetime: 720,
      height: 40,
      radiusX: 32,
      radiusY: 42,
      groundShock: true,
      level: "low",
    },
    rikiRise: {
      name: "重拍上挑",
      command: "Y / 2P 小键盘+",
      category: "special",
      rikiOnly: true,
      ground: true,
      cost: 25,
      duration: 760,
      start: 90,
      end: 220,
      damage: 16,
      stun: 390,
      push: 90,
      reach: 160,
      vertical: 240,
      launch: 380,
    },
    rikiCalibrate: {
      name: "节拍校准",
      command: "G / 2P Delete",
      category: "support",
      rikiOnly: true,
      ground: true,
      cost: 25,
      duration: 800,
      start: 300,
      end: 310,
      damage: 0,
      recast: 8000,
    },
    rikiEight: {
      name: "八拍过门",
      command: "L / 2P 小键盘3",
      category: "special",
      rikiOnly: true,
      ground: true,
      cost: 60,
      duration: 1450,
      start: 180,
      end: 1110,
      damage: 29,
      stun: 300,
      push: 8,
      reach: 220,
      cancelAt: 1020,
      pulses: Array.from({ length: 8 }, (_, i) => ({
        at: 180 + i * 120,
        damage: i === 7 ? 8 : 3,
        reach: 220,
        ...(i === 7 ? { push: 150, knockdown: 650 } : {}),
      })),
    },
    rikiSuper: {
      name: "哈？哈？哈？·全场共振",
      command: "P / 2P 小键盘8",
      category: "super",
      rikiOnly: true,
      ground: true,
      cost: 100,
      duration: 4400,
      start: 500,
      end: 3690,
      damage: 48,
      stun: 500,
      push: 30,
      reach: 420,
      vertical: 280,
      invuln: 100,
      pulses: [
        { at: 500, damage: 8, reach: 300, chip: 2 },
        { at: 1800, damage: 12, reach: 360, chip: 2 },
        {
          at: 3600,
          damage: 28,
          reach: 420,
          push: 300,
          knockdown: 750,
          chip: 4,
        },
      ],
    },
  });
  for (const [name, changes] of Object.entries({
    rikiRoll: { hitRecovery: 100 },
    rikiRush: { dashSpeed: 1220, pull: true },
    rikiOverhead: { stun: 440 },
    rikiShock: { shots: [220, 410], end: 430 },
    rikiRise: { vertical: 290, follow: true },
  })) {
    const source = MOVES[name];
    MOVES[name + "Boost"] = {
      ...source,
      ...changes,
      name: source.name + "·四拍强化",
      internal: true,
      boosted: true,
      base: name,
      ...(source.pulses
        ? { pulses: source.pulses.map((p) => ({ ...p })) }
        : {}),
    };
  }
  MOVES.rikiShockExtra = {
    ...MOVES.rikiShock,
    name: "四拍·追加低音",
    internal: true,
    resonanceHits: MOVES.rikiShockBoost.shots!.length,
    damage: 8,
    chip: 1,
  };
}
